-- The public monitoring views in this account are TRANSACTIONS and ENGINES.
-- The agent's own audit retains the exact PyRel, runtime hash, and correlation IDs.
USE DATABASE ALAA_RELAPP_PERSISTENCE;
USE SCHEMA PE_DEAL_GRAPH_EXPERIMENT_CORPORATE_AGENT;

SELECT COUNT(*) AS PE_EMPLOYEES FROM TEAM_MEMBER;
SELECT COUNT(*) AS CAREER_RECORDS,
       AVG(DATEDIFF(day, START_DATE, COALESCE(END_DATE, '2026-10-01'::DATE)))/365.25 AS AVG_TENURE_YEARS
FROM TEAM_ROLE_HISTORY;
SELECT PERSON_ID, COUNT(DISTINCT ORG_ID) AS PREVIOUS_CORPORATE_EMPLOYERS
FROM TEAM_ROLE_HISTORY WHERE ORG_ID <> 'PE_FIRM_NORTHWIND'
GROUP BY PERSON_ID ORDER BY PERSON_ID;

SELECT REQUEST_ID, STARTED_AT, STATUS, TARGET_ID, SOURCE_ID, PYREL_CODE,
       PYREL_SHA256, RUNTIME_SHA256, RAI_TRANSACTION_IDS, SNOWFLAKE_QUERY_IDS, SNOWFLAKE_SESSION_ID,
       RESULT, ERROR
FROM QUERY_AUDIT ORDER BY STARTED_AT DESC;

WITH REQUEST_TRANSACTIONS AS (
  SELECT A.REQUEST_ID, A.TARGET_ID, A.SOURCE_ID, F.VALUE::VARCHAR AS TRANSACTION_ID
  FROM QUERY_AUDIT A, LATERAL FLATTEN(INPUT => A.RAI_TRANSACTION_IDS) F
  WHERE A.STARTED_AT >= DATEADD(day, -7, CURRENT_TIMESTAMP())
)
SELECT A.*, T.STATE, T.CREATED_ON, T.FINISHED_AT, T.DURATION,
       T.ENGINE_NAME, E.STATUS AS ENGINE_STATUS, E.SIZE, E.AUTO_SUSPEND_MINS
FROM REQUEST_TRANSACTIONS A
JOIN RELATIONALAI.API.TRANSACTIONS T ON T.ID = A.TRANSACTION_ID
LEFT JOIN RELATIONALAI.API.ENGINES E ON E.NAME = T.ENGINE_NAME
ORDER BY T.CREATED_ON DESC;

SELECT NAME, ID, STATUS, SIZE, VERSION, AUTO_SUSPEND_MINS
FROM RELATIONALAI.API.ENGINES
WHERE NAME = 'alaa_pe_deal_graph_experiment';

-- Public history exposes the parent tool CALL. Some native-app child queries
-- are absent from this role's information-schema history; use TRANSACTIONS above
-- for their completed native execution records. Join each CALL by session/time.
SELECT A.REQUEST_ID, Q.QUERY_ID, Q.QUERY_TYPE, Q.EXECUTION_STATUS,
       Q.START_TIME, Q.TOTAL_ELAPSED_TIME, Q.QUERY_TEXT
FROM TABLE(ALAA_RELAPP_PERSISTENCE.INFORMATION_SCHEMA.QUERY_HISTORY_BY_USER(
  END_TIME_RANGE_START => DATEADD(hour, -4, CURRENT_TIMESTAMP()), RESULT_LIMIT => 10000,
  INCLUDE_CLIENT_GENERATED_STATEMENT => TRUE)) Q
JOIN QUERY_AUDIT A ON Q.SESSION_ID = A.SNOWFLAKE_SESSION_ID
  AND Q.START_TIME <= A.STARTED_AT AND Q.END_TIME >= A.COMPLETED_AT
WHERE Q.QUERY_TEXT ILIKE 'CALL%CORPORATE_AGENT.EXECUTE_PYREL%'
ORDER BY Q.START_TIME DESC;

-- Native v2 analytics are published only after independent validation.
SELECT RUN_ID, AS_OF, SCORING_VERSION, COMPUTED_AT, METADATA_JSON
FROM NETWORK_RUNS_V2 ORDER BY COMPUTED_AT DESC;

SELECT ID, STATE, ENGINE_NAME, DURATION,
       ATTRIBUTES:agent_request_id::STRING AS AGENT_REQUEST_ID,
       ATTRIBUTES:analytics_run_id::STRING AS ANALYTICS_RUN_ID,
       ATTRIBUTES:explorer_request_id::STRING AS EXPLORER_REQUEST_ID
FROM RELATIONALAI.API.TRANSACTIONS
WHERE ENGINE_NAME = 'alaa_pe_deal_graph_experiment'
  AND CREATED_ON >= DATEADD(day, -1, CURRENT_TIMESTAMP())
  AND (ATTRIBUTES:agent_request_id IS NOT NULL
    OR ATTRIBUTES:analytics_run_id IS NOT NULL
    OR ATTRIBUTES:explorer_request_id IS NOT NULL)
ORDER BY CREATED_ON DESC;
